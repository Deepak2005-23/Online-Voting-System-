// Helper function to get candidates with any votes cast in this browser session
export function getStoredCandidates() {
  const localVotes = JSON.parse(localStorage.getItem('candidate_votes') || '{}')
  return TAMIL_NADU_CANDIDATES.map((c) => ({
    ...c,
    voteCount: (c.initialVotes || 0) + (localVotes[c.id] || 0)
  }))
}

// Record vote in localStorage
export function recordLocalVote(candidateId) {
  const localVotes = JSON.parse(localStorage.getItem('candidate_votes') || '{}')
  localVotes[candidateId] = (localVotes[candidateId] || 0) + 1
  localStorage.setItem('candidate_votes', JSON.stringify(localVotes))
  
  const chosenCandidate = TAMIL_NADU_CANDIDATES.find((c) => c.id === candidateId)
  if (chosenCandidate) {
    localStorage.setItem('voted_candidate', JSON.stringify({
      ...chosenCandidate,
      voteId: `TN-EVS-${new Date().getFullYear()}-${Math.random().toString(36).substring(2, 8).toUpperCase()}`,
      votedAt: new Date().toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'medium', timeStyle: 'short' })
    }))
  }
  return chosenCandidate
}

